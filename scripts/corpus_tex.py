"""Write the corpus strings as a LaTeX list for the paper's appendix.

    python scripts/corpus_tex.py   -> paper/corpus_strings.tex

Bib keys of the corpus are mapped to the keys used in paper/kirismiles.bib.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "specs" / "corpus" / "literature.json"
OUT = ROOT / "paper" / "corpus_strings.tex"
KEY = {"dias2017kirigami": "dias-sm-48-9087-2017",
       "shyu2015kirigami": "shyu-NatMat-14-785-2015",
       "hanakata2018accelerated": "hanakata-PRL-121-255304-2018",
       "hanakata2020forward": "hanakata-PRR-2-042006-2020",
       "rafsanjani2018skins": "rafsanjani-SR-3-7555-2018"}
# The paper shows one 'written' status; literature.json keeps exact/topology for the
# software check (exact = matches an independent generator of kirigami/geometry.py).
LABEL = {"exact": "written", "topology": "written", "approximate": "approximate",
         "instance": "instance", "not_expressed": "not yet"}


def tex(s):
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def main():
    entries = json.loads(SRC.read_text(encoding="utf-8"))["entries"]
    lines = [r"% generated by scripts/corpus_tex.py from specs/corpus/literature.json",
             r"\begin{enumerate}"]
    for e in entries:
        if "code" not in e:
            continue
        refs = ", ".join(KEY.get(k, k) for k in e["refs"])
        lines.append(rf"\item \emph{{{tex(e['design'])}}}~\cite{{{refs}}}; "
                     rf"${e['L']:g}\times{e['W']:g}$~mm, {len(e['code'])} characters.\\")
        lines.append(rf"\kstr{{{e['code']}}}")
    lines.append(r"\end{enumerate}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT, sum(1 for e in entries if "code" in e), "strings")


if __name__ == "__main__":
    main()
